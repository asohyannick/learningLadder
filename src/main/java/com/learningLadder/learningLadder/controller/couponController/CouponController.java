package com.learningLadder.learningLadder.controller.couponController;

import com.learningLadder.learningLadder.config.apiResponse.APIErrorResponse;
import com.learningLadder.learningLadder.config.apiResponse.APISuccessResponse;
import com.learningLadder.learningLadder.dto.couponDto.CouponPageResponseDto;
import com.learningLadder.learningLadder.dto.couponDto.CouponResponseDto;
import com.learningLadder.learningLadder.dto.couponDto.CreateCouponRequestDto;
import com.learningLadder.learningLadder.dto.couponDto.PagedQueryCouponRequestDto;
import com.learningLadder.learningLadder.dto.couponDto.RevokeCouponRequestDto;
import com.learningLadder.learningLadder.enums.couponStatus.CouponStatus;
import com.learningLadder.learningLadder.enums.discountType.DiscountType;
import com.learningLadder.learningLadder.service.shoppingCartService.CouponService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.media.Content;
import io.swagger.v3.oas.annotations.media.Schema;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.responses.ApiResponses;
import io.swagger.v3.oas.annotations.security.SecurityRequirement;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import lombok.RequiredArgsConstructor;
import org.springdoc.core.annotations.ParameterObject;
import org.springframework.http.HttpStatus;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.security.core.Authentication;
import org.springframework.security.core.GrantedAuthority;
import org.springframework.security.core.annotation.AuthenticationPrincipal;
import org.springframework.validation.annotation.Validated;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.ModelAttribute;
import org.springframework.web.bind.annotation.PatchMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;
import org.springframework.web.servlet.support.ServletUriComponentsBuilder;

import java.time.ZoneOffset;
import java.time.format.DateTimeFormatter;
import java.util.List;
import java.util.UUID;

/**
 * Coupons are generated by the server and issued by administrators or instructors.
 * Students apply them through POST /shopping-cart/coupon and can list theirs at /coupons/mine.
 */
@RestController
@Validated
@RequiredArgsConstructor
@RequestMapping("/api/${app.api.version}/coupons")
@SecurityRequirement(name = "bearerAuth")
@Tag(
        name = "Coupon Management Endpoints",
        description = """
                Administrators issue platform-wide or course coupons; instructors issue coupons for the courses they
                teach. The server generates the code (e.g. LL-7KQ2-M9XD), every coupon has an expiration date,
                and a coupon can be revoked at any time: it is then removed from every open cart."""
)
public class CouponController {

    /** Keep in sync with COUPON_ISSUER_ROLES in SecurityConfig. */
    private static final String ISSUERS =
            "hasAnyRole('SUPER_ADMIN', 'ADMIN', 'IT_ADMIN', 'LECTURER', 'PROFESSOR', 'ASSISTANT_LECTURER')";

    private static final DateTimeFormatter DATE_TIME =
            DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm 'UTC'").withZone(ZoneOffset.UTC);

    private final CouponService couponService;

    @PostMapping(consumes = MediaType.APPLICATION_JSON_VALUE, produces = MediaType.APPLICATION_JSON_VALUE)
    @PreAuthorize(ISSUERS)
    @Operation(summary = "Issue a coupon",
            description = """
                    The server generates the code: do not send one. expiresAt is required (max 365 days).
                    Instructors must give a courseId for a course they teach. assignedUserId limits the coupon to one
                    student (single use by default). PERCENTAGE values are 1-100 and can be capped with maxDiscountAmount.""")
    @ApiResponses({
            @ApiResponse(responseCode = "201", description = "Coupon issued; the response contains the code"),
            @ApiResponse(responseCode = "400", description = "Validation failed",
                    content = @Content(mediaType = MediaType.APPLICATION_JSON_VALUE,
                            schema = @Schema(implementation = APIErrorResponse.class))),
            @ApiResponse(responseCode = "403", description = "Not an administrator, or not the course's instructor",
                    content = @Content(mediaType = MediaType.APPLICATION_JSON_VALUE,
                            schema = @Schema(implementation = APIErrorResponse.class))),
            @ApiResponse(responseCode = "404", description = "Course or student not found",
                    content = @Content(mediaType = MediaType.APPLICATION_JSON_VALUE,
                            schema = @Schema(implementation = APIErrorResponse.class)))
    })
    public ResponseEntity<APISuccessResponse<CouponResponseDto>> issueCoupon(
            @Valid @RequestBody CreateCouponRequestDto request,
            @Parameter(hidden = true) @AuthenticationPrincipal(expression = "id") UUID currentUserId,
            @Parameter(hidden = true) Authentication authentication) {

        CouponResponseDto coupon = couponService.issueCoupon(request, currentUserId, authorities(authentication));

        String value = coupon.discountType() == DiscountType.PERCENTAGE
                ? coupon.discountValue().stripTrailingZeros().toPlainString() + "% off"
                : coupon.discountValue().toPlainString() + " " + coupon.currency() + " off";
        String audience = coupon.assignedUserId() != null
                ? "Give this code to the student it is assigned to."
                : "Share this code with your students.";

        return ResponseEntity.status(HttpStatus.CREATED).body(APISuccessResponse.created(
                "Coupon " + coupon.code() + " created: " + value + ", valid until "
                        + DATE_TIME.format(coupon.expiresAt()) + ". " + audience,
                coupon, currentPath()));
    }

    @PatchMapping(value = "/{id}/revoke", consumes = MediaType.APPLICATION_JSON_VALUE,
            produces = MediaType.APPLICATION_JSON_VALUE)
    @PreAuthorize(ISSUERS)
    @Operation(summary = "Revoke a coupon",
            description = "Administrators can revoke any coupon; instructors only the coupons they issued. "
                    + "The coupon stops working immediately and is removed from every open cart.")
    @ApiResponses({
            @ApiResponse(responseCode = "200", description = "Coupon revoked"),
            @ApiResponse(responseCode = "403", description = "Not allowed to manage this coupon",
                    content = @Content(mediaType = MediaType.APPLICATION_JSON_VALUE,
                            schema = @Schema(implementation = APIErrorResponse.class))),
            @ApiResponse(responseCode = "404", description = "Coupon not found",
                    content = @Content(mediaType = MediaType.APPLICATION_JSON_VALUE,
                            schema = @Schema(implementation = APIErrorResponse.class))),
            @ApiResponse(responseCode = "409", description = "Already revoked",
                    content = @Content(mediaType = MediaType.APPLICATION_JSON_VALUE,
                            schema = @Schema(implementation = APIErrorResponse.class)))
    })
    public ResponseEntity<APISuccessResponse<CouponResponseDto>> revokeCoupon(
            @Parameter(description = "Coupon id") @PathVariable UUID id,
            @Valid @RequestBody RevokeCouponRequestDto request,
            @Parameter(hidden = true) @AuthenticationPrincipal(expression = "id") UUID currentUserId,
            @Parameter(hidden = true) Authentication authentication) {

        CouponResponseDto coupon = couponService.revokeCoupon(id, request, currentUserId, authorities(authentication));

        return ResponseEntity.ok(APISuccessResponse.ok(
                "Coupon " + coupon.code() + " revoked. It can no longer be used and was removed from open carts.",
                coupon, currentPath()));
    }

    @GetMapping(value = "/mine", produces = MediaType.APPLICATION_JSON_VALUE)
    @PreAuthorize("isAuthenticated()")
    @Operation(summary = "My coupons",
            description = "Coupons assigned to you. Use usableOnly=true to list only the codes you can apply now.")
    @ApiResponse(responseCode = "200", description = "Page of coupons")
    public ResponseEntity<APISuccessResponse<CouponPageResponseDto>> fetchMyCoupons(
            @Valid @ParameterObject @ModelAttribute PagedQueryCouponRequestDto query,
            @Parameter(hidden = true) @AuthenticationPrincipal(expression = "id") UUID currentUserId) {

        CouponPageResponseDto result = couponService.fetchMyCoupons(query, currentUserId);

        return ResponseEntity.ok(APISuccessResponse.ok(
                result.totalElements() == 0 ? "You have no coupons" : "You have " + result.totalElements() + " coupon(s)",
                result, currentPath()));
    }

    @GetMapping(produces = MediaType.APPLICATION_JSON_VALUE)
    @PreAuthorize(ISSUERS)
    @Operation(summary = "List coupons",
            description = "Administrators see all coupons; instructors only the coupons they issued. "
                    + "Filters: status, courseId, assignedUserId, createdBy, usableOnly, expiresFrom/To.")
    @ApiResponses({
            @ApiResponse(responseCode = "200", description = "Page of coupons"),
            @ApiResponse(responseCode = "403", description = "Not an administrator or instructor",
                    content = @Content(mediaType = MediaType.APPLICATION_JSON_VALUE,
                            schema = @Schema(implementation = APIErrorResponse.class)))
    })
    public ResponseEntity<APISuccessResponse<CouponPageResponseDto>> fetchCoupons(
            @Valid @ParameterObject @ModelAttribute PagedQueryCouponRequestDto query,
            @Parameter(hidden = true) @AuthenticationPrincipal(expression = "id") UUID currentUserId,
            @Parameter(hidden = true) Authentication authentication) {

        CouponPageResponseDto result = couponService.fetchCoupons(query, currentUserId, authorities(authentication));

        return ResponseEntity.ok(APISuccessResponse.ok(
                result.totalElements() == 0 ? "No coupons found" : result.totalElements() + " coupon(s) found",
                result, currentPath()));
    }

    @GetMapping(value = "/{id}", produces = MediaType.APPLICATION_JSON_VALUE)
    @PreAuthorize(ISSUERS)
    @Operation(summary = "Fetch a coupon", description = "Administrators: any coupon. Instructors: their own.")
    @ApiResponses({
            @ApiResponse(responseCode = "200", description = "The coupon"),
            @ApiResponse(responseCode = "403", description = "Not allowed to view this coupon",
                    content = @Content(mediaType = MediaType.APPLICATION_JSON_VALUE,
                            schema = @Schema(implementation = APIErrorResponse.class))),
            @ApiResponse(responseCode = "404", description = "Coupon not found",
                    content = @Content(mediaType = MediaType.APPLICATION_JSON_VALUE,
                            schema = @Schema(implementation = APIErrorResponse.class)))
    })
    public ResponseEntity<APISuccessResponse<CouponResponseDto>> fetchCoupon(
            @Parameter(description = "Coupon id") @PathVariable UUID id,
            @Parameter(hidden = true) @AuthenticationPrincipal(expression = "id") UUID currentUserId,
            @Parameter(hidden = true) Authentication authentication) {

        CouponResponseDto coupon = couponService.fetchCoupon(id, currentUserId, authorities(authentication));

        String reason;
        if (coupon.usable()) {
            reason = null;
        } else if (coupon.status() == CouponStatus.REVOKED) {
            reason = "revoked";
        } else if (coupon.expired()) {
            reason = "expired";
        } else if (coupon.remainingRedemptions() != null && coupon.remainingRedemptions() == 0) {
            reason = "no uses left";
        } else {
            reason = "not active yet";
        }
        String message = reason == null ? "Coupon fetched: currently usable"
                : "Coupon fetched: not usable (" + reason + ")";
        return ResponseEntity.ok(APISuccessResponse.ok(message, coupon, currentPath()));
    }

    private static List<String> authorities(Authentication authentication) {
        return authentication == null ? List.of()
                : authentication.getAuthorities().stream().map(GrantedAuthority::getAuthority).toList();
    }

    private static String currentPath() {
        return ServletUriComponentsBuilder.fromCurrentRequestUri().build().getPath();
    }
}