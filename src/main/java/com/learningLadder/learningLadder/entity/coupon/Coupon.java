package com.learningLadder.learningLadder.entity.coupon;

import com.learningLadder.learningLadder.entity.course.Course;
import com.learningLadder.learningLadder.entity.user.User;
import com.learningLadder.learningLadder.enums.couponStatus.CouponStatus;
import com.learningLadder.learningLadder.enums.discountType.DiscountType;
import jakarta.persistence.*;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.UUID;

/**
 * A discount code GENERATED BY THE SERVER and issued by an admin or an instructor.
 * Students never choose a code: they receive one and enter it in their cart.
 * <p>
 * A coupon is usable only when: status = ACTIVE, startsAt <= now < expiresAt,
 * and redemptions are left. Revoking it removes it from every open cart.
 */
@Entity(name = "coupon")
@Table(
        name = "coupons",
        uniqueConstraints = {
                @UniqueConstraint(name = "uk_coupon_code", columnNames = {"code"})
        },
        indexes = {
                @Index(name = "idx_coupon_status_expires", columnList = "status, expires_at"),
                @Index(name = "idx_coupon_course", columnList = "course_id"),
                @Index(name = "idx_coupon_assigned_user", columnList = "assigned_user_id"),
                @Index(name = "idx_coupon_created_by", columnList = "created_by")
        }
)
@Getter
@Setter
@NoArgsConstructor
public class Coupon {

    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    /** Server-generated, e.g. "LL-7KQ2-M9XD". Never chosen by a client. */
    @Column(name = "code", nullable = false, updatable = false, length = 20)
    private String code;

    @Column(name = "description", length = 255)
    private String description;

    // ---------- Discount ----------
    @Enumerated(EnumType.STRING)
    @Column(name = "discount_type", nullable = false, length = 20)
    private DiscountType discountType;

    /** Percentage (1-100) or fixed amount, depending on discountType. */
    @Column(name = "discount_value", nullable = false, precision = 12, scale = 2)
    private BigDecimal discountValue;

    /** Cap for percentage coupons (e.g. 20% but at most 50). */
    @Column(name = "max_discount_amount", precision = 12, scale = 2)
    private BigDecimal maxDiscountAmount;

    /** Currency of fixed amounts, caps and minimum totals. */
    @Column(name = "currency", nullable = false, length = 3)
    private String currency = "USD";

    /** Minimum amount to pay before the coupon applies. */
    @Column(name = "minimum_cart_total", precision = 12, scale = 2)
    private BigDecimal minimumCartTotal;

    // ---------- Scope ----------
    /** If set, the discount applies only to this course (and it must be in the cart). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "course_id")
    private Course course;

    /** If set, only this student can use the coupon. */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "assigned_user_id")
    private User assignedUser;

    // ---------- Validity ----------
    @Column(name = "starts_at", nullable = false)
    private Instant startsAt;

    /** Every coupon expires. */
    @Column(name = "expires_at", nullable = false)
    private Instant expiresAt;

    /** Null = unlimited uses until expiry. */
    @Column(name = "max_redemptions")
    private Integer maxRedemptions;

    /** Incremented at checkout (successful payment), not when added to a cart. */
    @Column(name = "redemption_count", nullable = false)
    private int redemptionCount = 0;

    // ---------- Revocation ----------
    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false, length = 20)
    private CouponStatus status = CouponStatus.ACTIVE;

    @Column(name = "revoked_at")
    private Instant revokedAt;

    @Column(name = "revoked_by")
    private UUID revokedBy;

    @Column(name = "revoke_reason", length = 500)
    private String revokeReason;

    // ---------- Issuer ----------
    /** User id of the admin or instructor who issued the coupon. */
    @Column(name = "created_by", nullable = false, updatable = false)
    private UUID createdBy;

    /** ADMIN or INSTRUCTOR: who may manage it later. */
    @Column(name = "issuer_role", nullable = false, length = 20)
    private String issuerRole;

    @Version
    @Column(name = "version", nullable = false)
    private Long version;

    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @UpdateTimestamp
    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;
}